enum BINS_T_ENTRY_STATES {
    BYTE_ENTRIES_T_IS_INUSE,
    BYTE_ENTRIES_T_IS_NOT_INUSE,
    OFFSET_ENTRIES_T_IS_INUSE,
    OFFSET_ENTRIES_T_IS_NOT_INUSE 
};
typedef struct byte_entries_t {
    void* ptr;
    struct offset_entries_t*    offset;
    struct byte_entries_t*      next;
    size_t                      bytes;
    unsigned char               _pad[4];
    enum BINS_T_ENTRY_STATES    state;
} byte_entries_t;

typedef struct offset_entries_t {
    byte_entries_t*             bytes;
    struct offset_entries_t*    next;
    size_t                      offset;
    unsigned char               _pad[4];
    enum BINS_T_ENTRY_STATES    state;
} offset_entries_t;

